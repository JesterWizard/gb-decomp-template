#!/usr/bin/env python3
"""Generate docs from the analysis DB.

  docs/banks.md          per-bank code/data bytes and naming progress
  docs/ram-map.md        every touched RAM address, who reads/writes it, its name
  docs/functions/<n>.md  one stub per NAMED function, prefilled with callers, callees
                         and RAM refs; the agent replaces the TODO with what it does

Existing function docs are never overwritten (only the machine-written "Facts" block
is refreshed), so prose written by hand is safe.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402
import tier  # noqa: E402

FACTS_START = "<!-- facts:start -->"
FACTS_END = "<!-- facts:end -->"


def facts(f: dict, ramnames: dict[str, str | None]) -> str:
    def lst(xs):
        return ", ".join(f"`{x}`" for x in xs) or "none"
    def rams(xs):
        return ", ".join(f"`{ramnames.get(x) or '$' + x}`" for x in xs) or "none"
    lines = [
        FACTS_START,
        f"- Address: `{f['key']}`  size: {f['size'] if f['size'] is not None else '?'} bytes  ({f['file']}:{f['line']})",
        f"- Callers: {lst(f['callers'])}",
        f"- Calls: {lst(f['callees'])}",
        f"- Tail-jumps to: {lst(f['tailjumps'])}",
        f"- Reads: {rams(f['reads'])}",
        f"- Writes: {rams(f['writes'])}",
    ]
    if f["bankswitch"]:
        lines.append("- Switches ROM bank")
    if f["indirect"]:
        lines.append("- Contains an indirect jump/call (`jp hl` / `call hl`): jump table or callback")
    lines.append(FACTS_END)
    return "\n".join(lines)


def main() -> int:
    funcs = common.load_json(common.ANALYSIS / "functions.json", {})
    if not funcs:
        print("error: run `make analyze` first", file=sys.stderr)
        return 1
    ram = common.load_json(common.ANALYSIS / "ram.json", {})
    banks = common.load_json(common.ANALYSIS / "banks.json", {})
    ramnames = {k: v.get("name") for k, v in ram.items()}
    tiers = tier.collect()

    out = ["# Banks\n", "Generated by `make document`.\n\n| Bank | Code bytes | Data bytes | Padding | Functions | Named |\n|---|---|---|---|---|---|\n"]
    for b in sorted(banks):
        d = banks[b]
        out.append(f"| {b} | {d['code_bytes']} | {d['data_bytes']} | {d.get('padding_bytes', 0)} | {d['functions']} | {d['named_functions']} |\n")
    (common.DOCS / "banks.md").write_text("".join(out))

    out = ["# RAM map\n", "Generated by `make document` from `analysis/ram.json`; names come from `symbols.py ram`.\n\n",
           "| Address | Region | Name | Readers | Writers |\n|---|---|---|---|---|\n"]
    for k, v in ram.items():
        out.append(f"| `${k}` | {v['region']} | {v['name'] or ''} | {len(v['readers'])} | {len(v['writers'])} |\n")
    (common.DOCS / "ram-map.md").write_text("".join(out))

    fdir = common.DOCS / "functions"
    fdir.mkdir(parents=True, exist_ok=True)
    made = 0
    for name, f in funcs.items():
        if tiers.get(name, "UNKNOWN") == "UNKNOWN":
            continue
        path = fdir / f"{name}.md"
        block = facts(f, ramnames)
        if path.is_file():
            text = path.read_text()
            if FACTS_START in text:
                text = re.sub(re.escape(FACTS_START) + r".*?" + re.escape(FACTS_END), lambda _m: block, text, flags=re.S)
            else:
                text += "\n" + block + "\n"
            path.write_text(text)
        else:
            path.write_text(f"# {name}\n\nTODO: what it does, inputs (registers / RAM), outputs, side effects.\n\n{block}\n")
            made += 1
    print(f"document: docs/banks.md, docs/ram-map.md, {made} new function stub(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
