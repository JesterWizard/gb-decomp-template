#!/usr/bin/env python3
"""Names, RAM symbols and code/data blocks: the single source of truth.

All names live in analysis/symbols.json, all block annotations in
analysis/blocks.json. Never hand-edit the asm to rename; use this tool, so every
reference follows and the rename is recorded with its evidence.

  symbols.py set 00:0184 ClearMem --confidence high --evidence "zeroes BC bytes at HL"
  symbols.py set Call_000_0184 ClearMem ...        # an auto label works as the key too
  symbols.py set 00:0153 MainLoop --kind label     # internal label, not a function
  symbols.py ram C000 wFrameCounter --size 1 --evidence "incremented in VBlankHandler"
  symbols.py block data 00:01a0 20 [--stride 3]     # also: code, text, padding, image
  symbols.py generate      # rewrite baserom.sym (consumed by mgbdis) from the json
  symbols.py apply         # rename identifiers / RAM operands inside src/*.asm
  symbols.py list [--unnamed]
  symbols.py import-sym FILE.sym   # e.g. an emulator-generated code map

Rules for names: unique, [A-Za-z_][A-Za-z0-9_]*, evidence required for anything
other than --confidence low. Prefixes: w=WRAM, h=HRAM, s=SRAM, v=VRAM, r=hardware reg.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402
from common import ANALYSIS, ROOT, SRC, IDENT_RE  # noqa: E402

SYMBOLS = ANALYSIS / "symbols.json"
BLOCKS = ANALYSIS / "blocks.json"
EXTRA = ROOT / "baserom.extra.sym"
GENERATED_HEADER = "; GENERATED by tools/decomp/symbols.py from analysis/symbols.json + blocks.json\n; Hand-written extras go in baserom.extra.sym. Do not edit this file.\n"
RAM_INC = SRC / "constants" / "ram.inc"


def load() -> dict:
    d = common.load_json(SYMBOLS, {"symbols": {}, "ram": {}})
    d.setdefault("symbols", {})
    d.setdefault("ram", {})
    return d


def norm_key(arg: str) -> str:
    """'00:0184' | 'Call_000_0184' | 'jr_000_0165' -> '00:0184'."""
    if re.match(r"^[0-9A-Fa-f]{2}:[0-9A-Fa-f]{4}$", arg):
        b, a = common.parse_key(arg)
        return common.key(b, a)
    k = common.auto_key(arg)
    if k:
        return k
    sym = common.parse_sym().get(arg)
    if sym:
        return common.key(*sym)
    sys.exit(f"error: cannot resolve {arg!r}; give BB:AAAA, an auto label, or build first so the .sym knows the name")


def check_name(name: str, data: dict, k: str | None) -> None:
    if not IDENT_RE.match(name):
        sys.exit(f"error: {name!r} is not a valid identifier")
    for other, s in data["symbols"].items():
        if s["name"] == name and other != k:
            sys.exit(f"error: {name} already names {other}")
    for other, s in data["ram"].items():
        if s["name"] == name and other != k:
            sys.exit(f"error: {name} already names RAM {other}")


def cmd_set(a) -> int:
    d = load()
    k = norm_key(a.where)
    check_name(a.name, d, k)
    if a.confidence != "low" and not a.evidence:
        sys.exit("error: medium/high confidence needs at least one --evidence line")
    prev = d["symbols"].get(k, {})
    entry = {
        "name": a.name,
        "kind": a.kind,
        "confidence": a.confidence,
        "evidence": a.evidence or prev.get("evidence", []),
        # What the identifier currently is in src/ (the auto name until `apply` runs).
        "applied": prev.get("applied") or a.where if common.AUTO_RE.match(a.where) else prev.get("applied", ""),
    }
    d["symbols"][k] = entry
    common.save_json(SYMBOLS, d)
    print(f"set {k} = {a.name}  (run `symbols.py apply` and `make compare`)")
    return 0


def cmd_ram(a) -> int:
    d = load()
    addr = int(a.addr, 16)
    if not (0x8000 <= addr <= 0xFFFF):
        sys.exit("error: RAM address must be in $8000-$FFFF")
    k = f"{addr:04X}"
    check_name(a.name, d, k)
    if a.confidence != "low" and not a.evidence:
        sys.exit("error: medium/high confidence needs at least one --evidence line")
    d["ram"][k] = {"name": a.name, "size": a.size, "confidence": a.confidence, "evidence": a.evidence or []}
    common.save_json(SYMBOLS, d)
    print(f"ram {k} = {a.name} (size {a.size})")
    return 0


def cmd_block(a) -> int:
    b = common.load_json(BLOCKS, {"blocks": {}})
    k = norm_key(a.where)
    spec = f".{a.kind}:{int(a.length, 16):X}"
    if a.stride:
        spec += f":{a.stride}"
    b["blocks"][k] = spec
    common.save_json(BLOCKS, b)
    print(f"block {k} {spec}  (run `make disasm` to regenerate src/)")
    return 0


def cmd_generate(_a) -> int:
    d = load()
    b = common.load_json(BLOCKS, {"blocks": {}})
    lines: list[tuple[str, int, str]] = []
    for k, s in d["symbols"].items():
        bank, addr = common.parse_key(k)
        lines.append((k, 0, f"{k.lower()} {s['name']}"))
    for k, spec in b["blocks"].items():
        lines.append((k, 1, f"{k.lower()} {spec}"))
    lines.sort()
    text = GENERATED_HEADER + "".join(l[2] + "\n" for l in lines)
    if EXTRA.is_file():
        text += "\n; --- baserom.extra.sym ---\n" + EXTRA.read_text()
    (ROOT / "baserom.sym").write_text(text)
    print(f"wrote baserom.sym ({len(lines)} entries)")
    return 0


# ---------------------------------------------------------------------------
# apply: rewrite src/*.asm
# ---------------------------------------------------------------------------

_STR_SPLIT = re.compile(r'("(?:[^"\\]|\\.)*")')


def _code_part(line: str) -> tuple[str, str]:
    """(code, comment) with string literals preserved inside code."""
    inq = False
    for i, ch in enumerate(line):
        if ch == '"':
            inq = not inq
        if ch == ";" and not inq:
            return line[:i], line[i:]
    return line, ""


def _rename_idents(line: str, mapping: dict[str, str]) -> str:
    code, comment = _code_part(line)
    parts = _STR_SPLIT.split(code)
    for i in range(0, len(parts), 2):
        parts[i] = re.sub(r"\b[A-Za-z_][A-Za-z0-9_]*\b", lambda m: mapping.get(m.group(0), m.group(0)), parts[i])
    return "".join(parts) + comment


def _ram_operands(line: str, ram: dict[int, str], immediates: bool) -> str:
    code, comment = _code_part(line)
    if not code[:1].isspace():
        return line
    def mem(m: re.Match) -> str:
        v = int(m.group(1), 16)
        return f"[{ram[v]}]" if v in ram else m.group(0)
    code = re.sub(r"\[\s*\$([0-9A-Fa-f]{4})\s*\]", mem, code)
    code = re.sub(r"\[\s*\$([0-9A-Fa-f]{2})\s*\]", lambda m: f"[{ram[0xFF00 + int(m.group(1), 16)]}]" if (0xFF00 + int(m.group(1), 16)) in ram and code.lstrip().startswith("ldh") else m.group(0), code)
    if immediates:
        code = re.sub(r"^(\s*ld\s+(?:bc|de|hl|sp)\s*,\s*)\$([0-9A-Fa-f]{4})\s*$", lambda m: m.group(1) + ram[int(m.group(2), 16)] if int(m.group(2), 16) in ram else m.group(0), code)
    return code + comment


def cmd_apply(a) -> int:
    d = load()
    # identifier renames: applied (current) -> name
    mapping: dict[str, str] = {}
    known = set()
    for f in common.asm_files():
        for line in f.read_text().splitlines():
            m = common.LABEL_RE.match(line)
            if m:
                known.add(m.group(1))
    for k, s in d["symbols"].items():
        auto = None
        bank, addr = common.parse_key(k)
        cur = s.get("applied") or ""
        if not cur:
            # find the auto label for this address among defined labels
            for lab in known:
                if common.auto_key(lab) == k:
                    cur = lab
                    break
        if cur and cur != s["name"] and cur in known:
            mapping[cur] = s["name"]
            s["applied"] = s["name"]
        elif s["name"] in known:
            s["applied"] = s["name"]
        else:
            print(f"warning: no label found for {k} ({s['name']}); build or `make disasm` first", file=sys.stderr)
    ram = {int(k, 16): v["name"] for k, v in d["ram"].items()}
    changed = 0
    for f in common.asm_files():
        old = f.read_text()
        new_lines = []
        for line in old.splitlines():
            new = _rename_idents(line, mapping) if mapping else line
            if ram:
                new = _ram_operands(new, ram, a.immediates)
            new_lines.append(new)
        new = "\n".join(new_lines) + ("\n" if old.endswith("\n") else "")
        if new != old:
            f.write_text(new)
            changed += 1
    write_ram_inc(d)
    common.save_json(SYMBOLS, d)
    print(f"apply: {len(mapping)} rename(s), {len(ram)} RAM symbol(s), {changed} file(s) changed")
    return 0


def write_ram_inc(d: dict) -> None:
    if not d["ram"]:
        return
    RAM_INC.parent.mkdir(parents=True, exist_ok=True)
    out = ["; GENERATED by tools/decomp/symbols.py apply from analysis/symbols.json (ram). Do not edit.\n"]
    for k in sorted(d["ram"], key=lambda x: int(x, 16)):
        r = d["ram"][k]
        out.append(f"DEF {r['name']} EQU ${int(k, 16):04X}  ; size {r.get('size', 1)}, {r.get('confidence', 'low')}\n")
    RAM_INC.write_text("".join(out))
    game = SRC / "game.asm"
    if game.is_file():
        text = game.read_text()
        inc = 'INCLUDE "constants/ram.inc"\n'
        if inc not in text:
            text = re.sub(r'(INCLUDE "hardware\.inc"\n)', r"\1" + inc, text, count=1)
            game.write_text(text)


def cmd_list(a) -> int:
    d = load()
    if a.unnamed:
        syms = common.parse_sym()
        named = {common.parse_key(k) for k in d["symbols"]}
        for name, (b, ad) in sorted(syms.items(), key=lambda x: x[1]):
            if common.AUTO_RE.match(name) and (b, ad) not in named:
                print(f"{common.key(b, ad)} {name}")
        return 0
    for k in sorted(d["symbols"]):
        s = d["symbols"][k]
        print(f"{k} {s['name']:<32} {s['kind']:<8} {s['confidence']}")
    for k in sorted(d["ram"], key=lambda x: int(x, 16)):
        r = d["ram"][k]
        print(f"ram {k} {r['name']:<28} size {r.get('size', 1)}")
    return 0


def cmd_import(a) -> int:
    d = load()
    n = 0
    for line in Path(a.file).read_text().splitlines():
        m = re.match(r"^([0-9A-Fa-f]{2,3}):([0-9A-Fa-f]{4})\s+([A-Za-z_][A-Za-z0-9_]*)\s*$", line)
        if not m:
            continue
        k = common.key(int(m.group(1), 16), int(m.group(2), 16))
        if k in d["symbols"]:
            continue
        name = m.group(3)
        try:
            check_name(name, d, k)
        except SystemExit:
            continue
        d["symbols"][k] = {"name": name, "kind": "function", "confidence": "low", "evidence": [f"imported from {Path(a.file).name}"], "applied": ""}
        n += 1
    common.save_json(SYMBOLS, d)
    print(f"imported {n} symbol(s)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("set"); p.add_argument("where"); p.add_argument("name")
    p.add_argument("--kind", choices=("function", "label", "data"), default="function")
    p.add_argument("--confidence", choices=("low", "medium", "high"), default="low")
    p.add_argument("--evidence", action="append")
    p.set_defaults(fn=cmd_set)
    p = sub.add_parser("ram"); p.add_argument("addr"); p.add_argument("name")
    p.add_argument("--size", type=int, default=1)
    p.add_argument("--confidence", choices=("low", "medium", "high"), default="low")
    p.add_argument("--evidence", action="append")
    p.set_defaults(fn=cmd_ram)
    p = sub.add_parser("block"); p.add_argument("kind", choices=("code", "data", "text", "padding", "image"))
    p.add_argument("where"); p.add_argument("length", help="hex length in bytes")
    p.add_argument("--stride", type=int)
    p.set_defaults(fn=cmd_block)
    sub.add_parser("generate").set_defaults(fn=cmd_generate)
    p = sub.add_parser("apply"); p.add_argument("--immediates", action="store_true", help="also rename `ld rr, $xxxx` immediates that equal a RAM symbol")
    p.set_defaults(fn=cmd_apply)
    p = sub.add_parser("list"); p.add_argument("--unnamed", action="store_true"); p.set_defaults(fn=cmd_list)
    p = sub.add_parser("import-sym"); p.add_argument("file"); p.set_defaults(fn=cmd_import)
    a = ap.parse_args()
    return a.fn(a)


if __name__ == "__main__":
    raise SystemExit(main())
